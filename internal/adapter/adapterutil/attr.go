package adapterutil

// TopologyKey — общий ключ в Snapshot.Topology, под которым adapters
// публикуют дискриминатор топологии (standalone/cluster/replica_set/...).
// Значения остаются engine-специфичными; общий только ключ.
const TopologyKey = "topology"

// AuthenticationKey — общий ключ в Snapshot.Topology, под которым adapter
// сообщает, аутентифицирует ли целевая система клиентов ВООБЩЕ.
//
// Это не то же самое, что «настроена ли авторизация». Кластер, принимающий
// анонимные соединения, отдаёт данные любому, кто до него дотянулся, и
// управление правами на нём — фикция: grantor записывает ACL, которые никто
// не спрашивает. Признак обязан быть виден в подключении, а не выводиться
// оператором из отсутствия ошибок.
//
// Значение — bool: false означает «аутентификации нет». Отсутствие ключа
// означает «adapter не сообщает», и finding не выставляется: молчание не
// доказывает ни того, ни другого.
const AuthenticationKey = "authentication_enabled"

// StringAttr читает строковый атрибут connection; отсутствие, неверный тип или
// пустое значение дают пустую строку. Guard на непустоту делает поведение
// единообразным для всех adapters (пустой атрибут трактуется как «не задан»).
func StringAttr(attrs map[string]any, key string) string {
	if v, ok := attrs[key].(string); ok && v != "" {
		return v
	}
	return ""
}
